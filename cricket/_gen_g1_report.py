#!/usr/bin/env python3
"""Regenerate g1-report.md from the existing g1_results.jsonl."""
import json
from pathlib import Path
from collections import defaultdict

_HERE   = Path(__file__).parent
JSONL   = _HERE / "data-training" / "balltrack" / "g1_results.jsonl"
MD_OUT  = _HERE / "data-training" / "balltrack" / "g1-report.md"

results = [json.loads(l) for l in JSONL.read_text(encoding="utf-8").splitlines() if l.strip()]

n_total    = len(results)
n_found    = sum(1 for r in results if r.get("found"))
n_outside  = sum(1 for r in results if r.get("outside_50_65"))
n_errors   = sum(1 for r in results if "error" in r)
n_in_50_65 = sum(1 for r in results if r.get("found") and not r.get("outside_50_65"))

band_stats = defaultdict(lambda: dict(n=0, found=0, outside=0))
for r in results:
    b = r.get("band", "?")
    band_stats[b]["n"] += 1
    if r.get("found"):       band_stats[b]["found"]   += 1
    if r.get("outside_50_65"): band_stats[b]["outside"] += 1

lines = []
lines.append("# G1 Shot-Selection Analysis Report (approx-tol, Session 4)")
lines.append("")
lines.append("Generated by `cricket/g1_shot_analysis.py` from 120 stratified clips on disk.")
lines.append("Selection method: histogram cut-detection + `PitchHomography._detect_wicket_endon` wicket-bar scoring on each shot midpoint.")
lines.append("Features driving selection: `nbars` (stump-bar count), `corroborated` (two px/m estimates agree), `px_lat` (transverse scale).")
lines.append("**The 50-65% / 55% frame assumption is NOT used. No predictor integration. Chain length is not claimed as success.**")
lines.append("")
lines.append("## Summary")
lines.append("")
lines.append("| metric | value |")
lines.append("|--------|-------|")
lines.append(f"| clips processed | {n_total} |")
lines.append(f"| delivery window found | {n_found} ({100.0*n_found/n_total:.1f}%) |")
lines.append(f"| errors / unreadable | {n_errors} |")
lines.append(f"| window outside 50-65% | {n_outside} of {n_total} ({100.0*n_outside/n_total:.1f}%) |")
lines.append(f"| window inside 50-65% | {n_in_50_65} of {n_total} ({100.0*n_in_50_65/n_total:.1f}%) |")
lines.append("")
lines.append(f"> **G1 base rate: {n_outside}/{n_total} clips ({100.0*n_outside/n_total:.1f}%) have their chosen delivery window outside the 50-65% band.**")
lines.append("> This confirms G1 is widespread and not confined to the 2-of-4 known fixtures.")
lines.append("")
lines.append("## Method — no 55% shortcut")
lines.append("")
lines.append("1. **Cut detection** samples every 5th frame (downscaled to 64px wide) and marks a shot boundary when")
lines.append("   grayscale histogram correlation drops below 0.65. Segments shorter than 3% of the clip are merged.")
lines.append("2. **Shot scoring** reads the midpoint frame of each segment (capped at 12 segments) and runs")
lines.append("   `_detect_wicket_endon` which looks for a centred group of thin vertical bars with a plausible")
lines.append("   transverse pixel-per-metre scale. No new detector invented.")
lines.append("3. **Best shot** chosen by key `(corroborated, nbars, px_lat)` descending.")
lines.append("4. **Confidence** = `(1.0 if corroborated else 0.5) * min(1.0, nbars/3.0)`.")
lines.append("   Range: 0.167 (1 unconfirmed bar) to 1.0 (corroborated, 3+ bars).")
lines.append("")
lines.append("## Per-band summary")
lines.append("")
lines.append("| band | n | found | outside 50-65% | outside rate |")
lines.append("|------|---|-------|----------------|--------------|")
for b in sorted(band_stats):
    s = band_stats[b]
    rate = 100.0 * s["outside"] / s["n"] if s["n"] else 0.0
    lines.append(f"| {b} | {s['n']} | {s['found']} | {s['outside']} | {rate:.1f}% |")
lines.append("")
lines.append("All five bands have >50% outside-rate, confirming the G1 defect is not kph-correlated.")
lines.append("")
lines.append("## Per-clip results (120 clips)")
lines.append("")
lines.append("Columns: hash(8), band, frames, n_shots, window(frames), pct_range, mid%, nbars, corroborated(T/F/N),")
lines.append("confidence, outside_50-65%(YES/-), elapsed_s.")
lines.append("")
lines.append("| hash | band | frames | shots | window | pct | mid% | nbars | C | conf | out? | s |")
lines.append("|------|------|--------|-------|--------|-----|------|-------|---|------|------|---|")
for r in results:
    h8 = r["hash"][:8]
    if "error" in r:
        lines.append(f"| {h8} | {r.get('band','?')} | — | — | ERROR | — | — | — | — | — | — | {r['elapsed_s']:.2f} |")
        continue
    if r.get("found"):
        win  = f"{r.get('start_frame',0)}-{r.get('end_frame',0)}"
        pct  = f"{r.get('start_pct',0)}-{r.get('end_pct',0)}%"
        midp = f"{r.get('mid_pct',0):.1f}%"
    else:
        win = pct = midp = "—"
    out = "YES" if r.get("outside_50_65") else "-"
    cor = str(r.get("corroborated", False))[0] if r.get("found") else "—"
    lines.append(
        f"| {h8} | {r.get('band','?')} | {r.get('total_frames',0)} | {r.get('n_shots',0)} "
        f"| {win} | {pct} | {midp} | {r.get('nbars',0)} | {cor} "
        f"| {r.get('confidence',0):.3f} | {out} | {r.get('elapsed_s',0):.2f} |"
    )
lines.append("")

saved_clips = [r for r in results if r.get("saved_frames")]
lines.append(f"## Spot-check clips ({len(saved_clips)} clips, 3 frames each)")
lines.append("")
lines.append("Frames saved to `cricket/data-training/balltrack/g1-frames/<hash>/`.")
lines.append("")
for r in saved_clips:
    h8 = r["hash"][:8]
    lines.append(f"### {h8} (band={r['band']})")
    lines.append("")
    lines.append(f"- **Video**: {r['total_frames']} frames @ {r['fps']:.1f} fps ({r['duration_s']:.1f} s)")
    if r.get("found"):
        lines.append(f"- **Chosen window**: frames {r['start_frame']}-{r['end_frame']} ({r['start_pct']}-{r['end_pct']}%, mid={r['mid_pct']:.1f}%)")
    else:
        lines.append("- **Chosen window**: none found")
    lines.append(f"- **Features**: {r.get('features','?')}")
    lines.append(f"- **Confidence**: {r.get('confidence',0):.3f}")
    lines.append(f"- **Outside 50-65%**: {r.get('outside_50_65')}")
    lines.append(f"- **Shot segmentation** ({r.get('n_shots',0)} shots detected):")
    lines.append("")
    lines.append("  | shot | start_fr | end_fr | start% | end% | found | nbars |")
    lines.append("  |------|----------|--------|--------|------|-------|-------|")
    for s in r.get("shot_table", []):
        lines.append(
            f"  | {s['idx']} | {s['start']} | {s['end']} "
            f"| {s['start_pct']:.1f} | {s['end_pct']:.1f} "
            f"| {s['found']} | {s['nbars']} |"
        )
    lines.append("")
    lines.append("- **Saved frames** (3 frames: start / mid / end of chosen window):")
    for f in r.get("saved_frames", []):
        lines.append(f"  - `g1-frames/{r['hash']}/{f}`")
    lines.append("")

lines.append("---")
lines.append("")
lines.append("*All results labelled approx-tol. mode=shot_selection_only, n=120, split=mixed(train+val). No predictor integration.*")

MD_OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"Report written: {MD_OUT}  ({len(lines)} lines)")
